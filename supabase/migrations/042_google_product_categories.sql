-- ------------------------------------------------------------
-- Google product categories
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.google_product_categories (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  level_1   TEXT,
  level_2   TEXT,
  level_3   TEXT,
  full_path TEXT
);

CREATE INDEX IF NOT EXISTS idx_gpc_level_1
  ON public.google_product_categories (level_1);
CREATE INDEX IF NOT EXISTS idx_gpc_level_1_2
  ON public.google_product_categories (level_1, level_2);

-- ------------------------------------------------------------
-- Facebook product categories (même structure, sans données ici)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fb_product_categories (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  level_1   TEXT,
  level_2   TEXT,
  level_3   TEXT,
  full_path TEXT
);

CREATE INDEX IF NOT EXISTS idx_fbpc_level_1
  ON public.fb_product_categories (level_1);
CREATE INDEX IF NOT EXISTS idx_fbpc_level_1_2
  ON public.fb_product_categories (level_1, level_2);

